export type TextKey = keyof typeof txt;

export function tr(lang: Lang, value: Localized, vars?: Record<string, string | number>) {
  let result = value[lang] ?? value.id;
  if (vars) {
    for (const [key, replacement] of Object.entries(vars)) {
      result = result.replaceAll(`{${key}}`, String(replacement));
    }
  }
  return result;
}
